const dictionaries: Record<Locale, Dictionary> = { en, bn };

export function normalizeLocale(value: string | null | undefined): Locale {
  if (value === "bn" || value === "bn-BD") return "bn";
  if (value === "en" || value === "en-US") return "en";
  return DEFAULT_LOCALE;
}

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

function intlLocale(locale: Locale): string {
  return locale === "bn" ? "bn-BD" : "en-US";
}

export function formatNumber(value: number, locale: Locale, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(intlLocale(locale), options).format(value);
}

export function formatCurrency(value: number, locale: Locale): string {
  return `৳${formatNumber(Number(value), locale, { maximumFractionDigits: 2 })}`;
}

export function formatMonth(dateStr: string, locale: Locale): string {
  return new Intl.DateTimeFormat(intlLocale(locale), {
    month: "long",
    year: "numeric",
    timeZone: "Asia/Dhaka",
  }).format(new Date(dateStr));
}

export function formatDate(dateStr: string, locale: Locale): string {
  return new Intl.DateTimeFormat(intlLocale(locale), { timeZone: "Asia/Dhaka" }).format(new Date(dateStr));
}

export function formatDateTime(dateStr: string, locale: Locale): string {
  return new Intl.DateTimeFormat(intlLocale(locale), {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Asia/Dhaka",
  }).format(new Date(dateStr));
}

export function formatPaymentMethod(value: string | null, locale: Locale, fallback: string): string {
  if (!value) return fallback;
  if (locale !== "bn") return value;

  const methods: Record<string, string> = {
    cash: "নগদ",
    bkash: "বিকাশ",
    nagad: "নগদ মোবাইল ব্যাংকিং",
    bank: "ব্যাংক",
    "bank transfer": "ব্যাংক ট্রান্সফার",
  };
  return methods[value.trim().toLocaleLowerCase()] ?? value;
}
